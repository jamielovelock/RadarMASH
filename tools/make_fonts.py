# Turns open-licensed TrueType fonts into the small anti-aliased bitmaps the radar draws text with, written out as
# core/fonts_data.cpp. That file is checked in, so building RadarMASH needs neither this script nor the font files.
# Run it only to add or change a font:
#     python3 -m venv build/venv && build/venv/bin/pip install pillow
#     build/venv/bin/python tools/make_fonts.py
# Fonts are downloaded from the Google Fonts repository into build/fonts. Each must allow redistribution in a modified
# form under its own name (so no "Reserved Font Name"); its licence goes in licenses/.
import os, sys, urllib.request, urllib.parse
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, "build", "fonts")
BASE = "https://raw.githubusercontent.com/google/fonts/main/ofl/"

# id, name shown in the settings page, folder and file in google/fonts, weight for variable fonts (or None)
FONTS = [
    ("b612mono", "B612 Mono (cockpit)", "b612mono", "B612Mono-Regular.ttf", None),
    ("jetbrains", "JetBrains Mono", "jetbrainsmono", "JetBrainsMono[wght].ttf", 500),
    ("roboto", "Roboto Condensed", "robotocondensed", "RobotoCondensed[wght].ttf", 500),
    ("vt323", "VT323 (terminal)", "vt323", "VT323-Regular.ttf", None),
]
BOX = [10, 16, 24]                       # line height in pixels of the small, medium and large sizes
CHARS = [chr(c) for c in range(32, 127)] + ["°"]      # printable ASCII, then the degree sign


def fetch(folder, filename):
    os.makedirs(CACHE, exist_ok=True)
    ttf, lic = os.path.join(CACHE, folder + ".ttf"), os.path.join(CACHE, folder + ".OFL.txt")
    for path, name in ((ttf, filename), (lic, "OFL.txt")):
        if not os.path.exists(path):
            urllib.request.urlretrieve(BASE + folder + "/" + urllib.parse.quote(name), path)
    text = open(lic, encoding="utf-8").read()
    assert "Reserved Font Name" not in text.split("\n\n")[0], folder + " reserves its name; pick another font"
    return ttf, text


def load(ttf, size, weight):
    f = ImageFont.truetype(ttf, size)
    if weight is not None:
        f.set_variation_by_axes([weight])
    return f


def extent(f):
    """Highest and lowest ink over all the characters, relative to the baseline."""
    top, bottom = 0, 0
    for ch in CHARS:
        b = f.getbbox(ch, anchor="ls")
        top, bottom = min(top, b[1]), max(bottom, b[3])
    return top, bottom


def face(ttf, box, weight):
    size = box * 2
    while True:                           # the largest size whose tallest and deepest glyphs still fit the line
        f = load(ttf, size, weight)
        top, bottom = extent(f)
        if bottom - top <= box or size <= 4:
            break
        size -= 1
    pad = (box - (bottom - top)) // 2     # centre what is left over
    glyphs, data = [], bytearray()
    for ch in CHARS:
        adv = max(1, round(f.getlength(ch)))
        b = f.getbbox(ch, anchor="ls")
        w = max(0, b[2] - b[0])
        img = Image.new("L", (max(w, 1), box), 0)
        ImageDraw.Draw(img).text((-b[0], pad - top), ch, font=f, fill=255, anchor="ls")
        offset = len(data)
        px = img.load()
        for y in range(box):              # 4 bits a pixel, two pixels a byte, each row starting on a byte
            for x in range(0, w, 2):
                hi = px[x, y] >> 4
                lo = px[x + 1, y] >> 4 if x + 1 < w else 0
                data.append((hi << 4) | lo)
        glyphs.append((offset, w, max(-128, min(127, b[0])), min(255, adv)))
    assert len(data) < 65536
    return size, glyphs, data


def main():
    out = ["// Generated by tools/make_fonts.py. Do not edit.",
           "// Bitmaps of open-licensed fonts; each font's licence is in licenses/. SPDX: OFL-1.1 for the font data.",
           '#include "font.h"', "", "namespace rm {", ""]
    table = []
    os.makedirs(os.path.join(ROOT, "licenses"), exist_ok=True)
    for fid, name, folder, filename, weight in FONTS:
        ttf, lic = fetch(folder, filename)
        open(os.path.join(ROOT, "licenses", "OFL-" + fid + ".txt"), "w", encoding="utf-8").write(lic)
        faces = []
        for tier, box in enumerate(BOX):
            size, glyphs, data = face(ttf, box, weight)
            tag = f"{fid}_{tier}"
            out.append(f"// {name}, {box} px line ({size} px font), {len(data)} bytes")
            out.append(f"static const uint8_t DATA_{tag}[] = {{")
            for i in range(0, len(data), 24):
                out.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
            out.append("};")
            out.append(f"static const Glyph GLYPHS_{tag}[] = {{")
            for i in range(0, len(glyphs), 6):
                out.append("  " + " ".join("{%d,%d,%d,%d}," % g for g in glyphs[i:i + 6]))
            out.append("};")
            out.append(f"static const FontFace FACE_{tag} = {{{box}, GLYPHS_{tag}, DATA_{tag}}};")
            out.append("")
            faces.append(f"&FACE_{tag}")
            print(f"{name:24s} {box:2d} px line: font size {size:2d}, {len(data):5d} bytes")
        table.append(f'  {{"{fid}", "{name}", {{{", ".join(faces)}}}}},')
    out.append("const Font FONTS[] = {")
    out.append('  {"classic", "Classic pixel", {nullptr, nullptr, nullptr}},      // the built-in 5x7 font, scaled')
    out += table
    out.append("};")
    out.append("const int FONT_COUNT = (int)(sizeof FONTS / sizeof FONTS[0]);")
    out += ["", "}  // namespace rm", ""]
    open(os.path.join(ROOT, "core", "fonts_data.cpp"), "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    main()
